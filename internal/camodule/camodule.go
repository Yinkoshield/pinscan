// Package camodule generates an open, auditable Magisk module that makes a
// research CA trusted system-wide on a rooted device. It is the self-serve path
// to CA trust (-mode system): no compiled or proprietary component — just the
// CA certificate and plain shell scripts the operator can read before flashing.
//
// On Android <= 13, Magisk overlays system/etc/security/cacerts automatically.
// On Android 14+, where the trust store moved to the read-only Conscrypt APEX,
// the module's service.sh overlays it with a directory holding the stock
// certificates plus the research CA. That overlay must run at late_start, not
// post-fs-data: apexd mounts the APEX after post-fs-data, so an earlier bind
// mount is silently discarded. The overlay is then injected into each zygote
// mount namespace with nsenter: app processes are forked from zygote and do not
// inherit a mount made later in the global namespace, so without that step the
// CA is visible to the shell but not to the app under test. service.sh verifies
// the CA is visible from zygote's namespace -- the one that decides whether an
// app trusts it -- and records the outcome in /data/local/tmp/pinscan-ca.log.
package camodule

import (
	"bytes"
	"crypto/md5" //nolint:gosec // OpenSSL subject_hash_old is defined in terms of MD5; not a security use.
	"crypto/x509"
	"encoding/binary"
	"encoding/pem"
	"fmt"
	"strings"
)

// File is one generated module file and whether it must be executable.
type File struct {
	Path       string
	Content    []byte
	Executable bool
}

// SubjectHashOld returns OpenSSL's legacy subject hash for cert — the name
// Android's cacerts store uses (`<hash>.0`). It is the little-endian uint32 of
// the first four bytes of MD5 over the certificate's raw DER subject.
func SubjectHashOld(cert *x509.Certificate) string {
	sum := md5.Sum(cert.RawSubject) //nolint:gosec // see package import note.
	return fmt.Sprintf("%08x", binary.LittleEndian.Uint32(sum[:4]))
}

// Generate builds the module file set for the CA in caPEM. The id and name
// label the Magisk module. The returned files are written verbatim by the caller.
func Generate(caPEM []byte, id, name string) ([]File, error) {
	cert, err := firstCert(caPEM)
	if err != nil {
		return nil, err
	}
	hash := SubjectHashOld(cert)
	certPEM := pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: cert.Raw})

	return []File{
		{Path: "module.prop", Content: moduleProp(id, name)},
		{Path: "post-fs-data.sh", Content: postFsData(), Executable: true},
		{Path: "service.sh", Content: service(hash), Executable: true},
		{Path: "system/etc/security/cacerts/" + hash + ".0", Content: certPEM},
		{Path: "cacert.pem", Content: certPEM},
		{Path: "README.md", Content: readme(id, hash, cert)},
	}, nil
}

// firstCert returns the first CERTIFICATE block in pemBytes.
func firstCert(pemBytes []byte) (*x509.Certificate, error) {
	for {
		var block *pem.Block
		block, pemBytes = pem.Decode(pemBytes)
		if block == nil {
			return nil, fmt.Errorf("camodule: no CERTIFICATE block in CA PEM")
		}
		if block.Type == "CERTIFICATE" {
			cert, err := x509.ParseCertificate(block.Bytes)
			if err != nil {
				return nil, fmt.Errorf("camodule: parse certificate: %w", err)
			}
			if !cert.IsCA {
				return nil, fmt.Errorf("camodule: certificate %q is not a CA", cert.Subject.CommonName)
			}
			return cert, nil
		}
	}
}

func moduleProp(id, name string) []byte {
	return []byte(strings.Join([]string{
		"id=" + id,
		"name=" + name,
		"version=v1",
		"versionCode=1",
		"author=generated by pinscan",
		"description=Trusts a research CA system-wide for authorized TLS-pinning assessment. Remove when finished.",
		"",
	}, "\n"))
}

// postFsData covers Android <= 13, where Magisk's own system/ overlay already
// applies the CA. The Android 14+ Conscrypt APEX overlay cannot run here:
// apexd mounts the APEX *after* post-fs-data, silently replacing any bind
// mount made at this stage. That work lives in service.sh (late_start).
func postFsData() []byte {
	return []byte(`#!/system/bin/sh
# pinscan research-CA system-trust module (generated; safe to read).
#
# Android <= 13: Magisk overlays system/etc/security/cacerts from this module's
# system/ directory automatically, so there is nothing to do here.
#
# Android 14+: the trust store moved into the read-only Conscrypt APEX, which
# apexd mounts AFTER this stage -- a bind mount made here would be discarded.
# See service.sh, which runs at late_start once the APEX is mounted.
exit 0
`)
}

// service generates the late_start script that overlays the Android 14+
// Conscrypt APEX trust store. The hash argument names the <hash>.0 trust-store
// file to install and then verify.
func service(hash string) []byte {
	return []byte(`#!/system/bin/sh
# pinscan research-CA system-trust module (generated; safe to read).
#
# Android 14+ keeps the CA trust store in the read-only Conscrypt APEX. Two
# things make that awkward, and both are handled here:
#
#   1. apexd mounts -- and re-mounts -- the APEX well after post-fs-data, so an
#      overlay applied early is silently discarded. Apply ours once boot has
#      completed, and re-apply if it is replaced later.
#   2. A mount in the global namespace never reaches apps: every app is forked
#      from zygote, which holds its own mount namespace. Inject the overlay
#      into each zygote namespace with nsenter.
#
# Neither step is optional: skip (1) and the overlay vanishes during boot; skip
# (2) and the CA is visible to the shell but not to the app under test, so every
# host reads inconclusive. The outcome is recorded in the log below.
MODDIR=${0%/*}
APEX=/apex/com.android.conscrypt/cacerts
WORK=/data/local/tmp/pinscan-cacerts
LOG=/data/local/tmp/pinscan-ca.log
CA=` + hash + `.0

log() { echo "$(date +%H:%M:%S) $*" >> "$LOG"; }
: > "$LOG"

# wait_until <seconds> <condition>: poll condition once a second, up to a limit.
wait_until() {
  _limit=$1
  _n=0
  while [ "$_n" -lt "$_limit" ]; do
    if eval "$2"; then
      return 0
    fi
    sleep 1
    _n=$((_n + 1))
  done
  return 1
}

if ! wait_until 120 '[ -d "$APEX" ]'; then
  log "no Conscrypt APEX: Android <= 13, the module system/ overlay applies"
  exit 0
fi
if ! wait_until 180 '[ "$(getprop sys.boot_completed)" = "1" ]'; then
  log "WARN: boot did not complete within 180s; applying the overlay anyway"
fi
sleep 5

# build assembles the replacement trust store: every stock certificate plus ours.
build() {
  # Never wipe $WORK while it is bind mounted over the APEX: the certificates
  # in it are in active use, and removing them breaks TLS system-wide.
  if grep -q " $APEX " /proc/mounts 2>/dev/null; then
    log "refusing to rebuild $WORK while it is mounted over $APEX"
    return 1
  fi
  rm -rf "$WORK"
  mkdir -p "$WORK"
  cp -f "$APEX"/* "$WORK"/ 2>/dev/null
  cp -f "$MODDIR/system/etc/security/cacerts/$CA" "$WORK"/ || return 1
  chown 0:0 "$WORK"/*
  chmod 644 "$WORK"/*
  chcon u:object_r:system_file:s0 "$WORK"/* 2>/dev/null
  return 0
}

# apply binds the store over the APEX globally and inside every zygote namespace,
# printing how many zygotes accepted it.
apply() {
  mount -o bind "$WORK" "$APEX" 2>/dev/null
  _count=0
  for _z in $(pidof zygote64 zygote 2>/dev/null); do
    if nsenter --mount=/proc/$_z/ns/mnt -- mount -o bind "$WORK" "$APEX" 2>/dev/null; then
      _count=$((_count + 1))
    fi
  done
  echo "$_count"
}

# trusted reports whether the CA is visible from every zygote namespace -- the
# only namespace whose view decides what an app trusts.
trusted() {
  _zs=$(pidof zygote64 zygote 2>/dev/null)
  [ -n "$_zs" ] || return 1
  for _z in $_zs; do
    nsenter --mount=/proc/$_z/ns/mnt -- test -f "$APEX/$CA" || return 1
  done
  return 0
}

if ! build; then
  log "FAIL: research CA $CA missing from the module"
  exit 1
fi
n=$(apply)
if trusted; then
  log "OK: $CA trusted in $n zygote namespace(s)"
else
  log "FAIL: $CA not visible from zygote after mount; apps will not trust it"
  exit 1
fi

# apexd may still re-mount the APEX, and zygote may restart; either silently
# drops the overlay. Watch for a bounded window and re-mount if that happens.
#
# This loop deliberately re-runs apply() only, never build(): $WORK is bind
# mounted over the live trust store, so deleting and refilling it would strip
# the certificates every process is currently using. Doing that crashes
# system_server repeatedly and Android's RescueParty reboots the device.
i=0
while [ "$i" -lt 24 ]; do
  sleep 5
  if ! trusted; then
    if apply >/dev/null && trusted; then
      log "re-applied: the overlay had been replaced"
    else
      log "WARN: overlay lost and could not be re-applied"
    fi
  fi
  i=$((i + 1))
done
`)
}

func readme(id, hash string, cert *x509.Certificate) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "# %s\n\n", id)
	fmt.Fprintf(&b, "Open Magisk module (generated by pinscan) that trusts a research CA\n")
	fmt.Fprintf(&b, "system-wide, so an app under test accepts certificates the pinscan proxy\n")
	fmt.Fprintf(&b, "mints. For **authorized** TLS-pinning assessment only; remove when done.\n\n")
	fmt.Fprintf(&b, "- CA subject: %s\n", cert.Subject)
	fmt.Fprintf(&b, "- Trust-store filename: %s.0\n\n", hash)
	fmt.Fprintf(&b, "## Install\n\n")
	fmt.Fprintf(&b, "Rooted device with Magisk. Push the module and reboot:\n\n")
	fmt.Fprintf(&b, "```sh\n")
	fmt.Fprintf(&b, "adb push %s /data/local/tmp/%s\n", id, id)
	fmt.Fprintf(&b, "# Separate su commands: a chained `su -c '... && ...'` is mangled by adb.\n")
	fmt.Fprintf(&b, "adb shell su -c 'rm -rf /data/adb/modules/%s'\n", id)
	fmt.Fprintf(&b, "adb shell su -c 'cp -r /data/local/tmp/%s /data/adb/modules/%s'\n", id, id)
	fmt.Fprintf(&b, "adb shell su -c 'chmod 755 /data/adb/modules/%s/post-fs-data.sh /data/adb/modules/%s/service.sh'\n", id, id)
	fmt.Fprintf(&b, "adb reboot\n")
	fmt.Fprintf(&b, "```\n\n")
	fmt.Fprintf(&b, "Then verify: `pinscan doctor <package>` and a short `pinscan scan -mode system`.\n")
	fmt.Fprintf(&b, "If hosts come back `inconclusive`, the app is not yet trusting the CA;\n")
	fmt.Fprintf(&b, "check `/data/local/tmp/pinscan-ca.log` for this module's own result line.\n")
	return b.Bytes()
}
